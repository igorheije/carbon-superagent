import { mkdirSync, rmSync, statSync } from "node:fs";
import path from "node:path";
import { buildCommand, parseMarkers, startExecutor, type ExecutorCommand, type ExecutorEvent, type RunningExecutor } from "../shared/executors";
import { LEASE_LOST, type ClaimedTask, type ResultRequest } from "../shared/worker-protocol";
import { backoffMs, BundleTooLarge, WorkerClientError, type SleepFn, type WorkerClient } from "./client";
import { cleanup, commitAll, deliverCode, prepareCode, type GitIdentity, type PreparedCode } from "./code";
import { gitTokenFor } from "./config";
import { clipEvent, relativize } from "./events";
import { answerPermission, createPermissionRelay, type PermissionRelay } from "./permissions";

/**
 * Runs one claimed task on the worker (WRK-03, WRK-05, CODE-01..03): get the code, run the
 * executor CLI, stream its events, keep the lease alive, honour cancel / lease loss, commit,
 * deliver (push or bundle) and report the result. Plain Node: no DB, no Next, no server-only.
 *
 * The git token only travels to code.ts (GIT_ASKPASS); nothing here logs it.
 */

/** "waiting": the agent asked a question; the panel parks the task until a human answers (RMT-02). */
export type RunOutcome = "done" | "failed" | "canceled" | "lease_lost" | "waiting";

export interface RunTaskDeps {
  readonly client: WorkerClient;
  /** Parent folder for clones and bundles of this worker. */
  readonly workDir: string;
  readonly gitToken?: string;
  /**
   * Hosts the git token may be sent to (CARBON_GIT_HOSTS). Empty/absent: the token is never sent,
   * so a remoteUrl chosen by the panel (or rewritten by the agent) cannot receive it.
   */
  readonly gitHosts?: readonly string[];
  /** Test hook: replaces the CLI the executor would spawn (keeps the parser and stdin prompt). */
  readonly executorOverride?: (command: ExecutorCommand) => ExecutorCommand;
  readonly now?: () => number;
  readonly log?: (message: string) => void;
  /** Aborted when the worker shuts down: the agent is stopped and the task reported as canceled. */
  readonly signal?: AbortSignal;
  /** Result bundles above this are not uploaded (the panel would answer 413 anyway). */
  readonly maxBundleMb?: number;
  readonly sleep?: SleepFn;
  readonly identity?: GitIdentity;
}

export const DEFAULT_MAX_BUNDLE_MB = 200;
const MB = 1024 * 1024;
const DEFAULT_IDENTITY: GitIdentity = { name: "Carbon Agent", email: "carbon@localhost" };
/** Attempts for one-shot calls (bundle download/upload, result) on retryable errors. */
const MAX_ATTEMPTS = 6;
/** Events still unacked after this go unsent: the result matters more than the last log lines. */
const FLUSH_TIMEOUT_MS = 60_000;

type Stop = { readonly kind: "canceled" | "lease_lost"; readonly reason: string };

const message = (error: unknown): string => (error instanceof Error ? error.message : String(error));
const lastLine = (text: string): string => text.split("\n").map((l) => l.trim()).filter(Boolean).at(-1) ?? "";
const safeName = (taskId: string): string => taskId.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 80) || "x";

/** Same commit subject as the local runner (runner.ts): "feat: <título> (<KEY>)"; key only when the panel sent no title. */
export function commitMessage(task: Pick<ClaimedTask, "key" | "title" | "executor">): string {
  const title = task.title?.trim();
  const subject = title ? `feat: ${title} (${task.key})` : `feat: ${task.key}`;
  return `${subject}\n\nGenerated by Carbon (${task.executor}).`;
}

const defaultSleep: SleepFn = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

/** Mutable bookkeeping of one run, owned by runClaimedTask. */
interface RunState {
  stop: Stop | null;
  executor: RunningExecutor | null;
  relay: PermissionRelay | null;
  asked: boolean;
  agentError: boolean;
}

export async function runClaimedTask(task: ClaimedTask, deps: RunTaskDeps): Promise<RunOutcome> {
  const { client } = deps;
  const log = deps.log ?? (() => undefined);
  const sleep = deps.sleep ?? defaultSleep;
  const id = task.taskId;
  const gitToken = task.code.transport === "git" ? gitTokenFor(task.code.remoteUrl, deps.gitToken, deps.gitHosts ?? []) : undefined;
  if (deps.gitToken && task.code.transport === "git" && !gitToken) log(`[${task.key}] remoto fora de CARBON_GIT_HOSTS (ou não https): token git não será enviado`);
  const state: RunState = { stop: null, executor: null, relay: null, asked: false, agentError: false };

  const halt = (stop: Stop): void => {
    if (state.stop) return;
    state.stop = stop;
    log(`[${task.key}] ${stop.kind === "canceled" ? "cancelando" : "lease perdido"}: ${stop.reason}`);
    state.relay?.stop();
    state.executor?.cancel();
  };

  /** Queues events for the panel, cut to the protocol limits. Never throws. */
  const emit = (events: readonly ExecutorEvent[]): void => {
    if (state.stop?.kind === "lease_lost") return;
    try {
      if (client.sendEvents(id, events.map(clipEvent)) === LEASE_LOST) halt({ kind: "lease_lost", reason: "o painel recusou os eventos" });
    } catch (error) {
      log(`[${task.key}] evento descartado: ${message(error)}`);
    }
  };

  async function retrying<T>(what: string, fn: () => Promise<T>): Promise<T> {
    for (let attempt = 0; ; attempt++) {
      try {
        return await fn();
      } catch (error) {
        const retryable = error instanceof WorkerClientError && error.retryable;
        if (!retryable || attempt + 1 >= MAX_ATTEMPTS) throw error;
        log(`[${task.key}] ${what}: ${message(error)} — tentando de novo`);
        await sleep(backoffMs(attempt, Math.random));
      }
    }
  }

  // ------------------------------------------------------------ heartbeat

  let beating = false;
  const beat = async (): Promise<void> => {
    if (beating) return;
    beating = true;
    try {
      const answer = await client.heartbeat(id);
      if (answer === LEASE_LOST) halt({ kind: "lease_lost", reason: "o painel retirou a tarefa deste worker" });
      else if (answer.cancel) halt({ kind: "canceled", reason: "pedido no painel" });
    } catch (error) {
      if (error instanceof WorkerClientError && error.retryable) log(`[${task.key}] heartbeat falhou (${message(error)}); tento no próximo ciclo`);
      else halt({ kind: "lease_lost", reason: `heartbeat recusado: ${message(error)}` });
    } finally {
      beating = false;
    }
  };
  const heartbeat = setInterval(() => void beat(), Math.max(1_000, Math.floor(task.leaseMs / 3)));
  const onShutdown = () => halt({ kind: "canceled", reason: "o worker foi encerrado" });
  if (deps.signal?.aborted) onShutdown();
  deps.signal?.addEventListener("abort", onShutdown, { once: true });

  // ------------------------------------------------------------ report

  /** Flushes events then posts the result. The outcome reflects what the panel accepted. */
  async function report(status: ResultRequest["status"], extra: { commit?: string | null; transport?: ResultRequest["transport"]; error?: string } = {}): Promise<RunOutcome> {
    if (state.stop?.kind === "lease_lost") return "lease_lost";
    let timer: ReturnType<typeof setTimeout> | undefined;
    const flushed = await Promise.race([
      client.flush(id).catch((error: unknown) => {
        log(`[${task.key}] eventos não entregues: ${message(error)}`);
        return "ok" as const;
      }),
      new Promise<"timeout">((resolve) => {
        timer = setTimeout(() => resolve("timeout"), FLUSH_TIMEOUT_MS);
      }),
    ]).finally(() => clearTimeout(timer));
    if (flushed === LEASE_LOST) return "lease_lost";
    if (flushed === "timeout") log(`[${task.key}] eventos ainda pendentes após ${FLUSH_TIMEOUT_MS / 1000}s; enviando o resultado mesmo assim`);
    const req: ResultRequest = {
      status,
      branch: task.code.branch,
      commit: extra.commit ?? null,
      transport: extra.transport ?? (task.code.transport === "git" ? "push" : "bundle"),
      ...(extra.error ? { error: extra.error.slice(0, 4000) } : {}),
    };
    try {
      const delivered = await retrying("result", () => client.result(id, req));
      if (delivered === LEASE_LOST) return "lease_lost";
      return status;
    } catch (error) {
      // 422: the panel could not import the result and already failed the task with the reason.
      log(`[${task.key}] o painel não aceitou o resultado: ${message(error)}`);
      return "failed";
    }
  }

  const fail = (reason: string): Promise<RunOutcome> => {
    log(`[${task.key}] falhou: ${reason}`);
    emit([{ type: "error", message: reason }]);
    return report("failed", { error: reason });
  };

  /** Ends the run when cancel or lease loss arrived; null to keep going. */
  const stopped = (): Promise<RunOutcome> | null => {
    if (!state.stop) return null;
    if (state.stop.kind === "lease_lost") return Promise.resolve("lease_lost");
    return report("canceled", { error: state.stop.reason });
  };

  // ------------------------------------------------------------ run

  mkdirSync(deps.workDir, { recursive: true });
  const baseBundle = path.join(path.resolve(deps.workDir), `task-${safeName(id)}.base.bundle`);
  let prepared: PreparedCode | null = null;
  try {
    log(`[${task.key}] começando (${task.executor}, ${task.code.transport})`);
    if (task.code.transport === "bundle") {
      try {
        if ((await retrying("download do bundle", () => client.downloadBundle(id, baseBundle))) === LEASE_LOST) {
          halt({ kind: "lease_lost", reason: "o painel recusou o download do bundle" });
        }
      } catch (error) {
        return (await stopped()) ?? (await fail(`não consegui baixar o código do painel: ${message(error)}`));
      }
    }
    const early = stopped();
    if (early) return await early;

    try {
      prepared = await prepareCode(task, deps.workDir, { bundleFile: baseBundle, gitToken });
    } catch (error) {
      return (await stopped()) ?? (await fail(`não consegui preparar o código: ${message(error)}`));
    } finally {
      rmSync(baseBundle, { force: true });
    }
    const afterPrepare = stopped();
    if (afterPrepare) return await afterPrepare;

    const clone = prepared.path;
    const built = buildCommand(task.executor, task.prompt, clone, task.settings, task.model, null);
    const command = deps.executorOverride ? deps.executorOverride(built) : built;
    const relay = createPermissionRelay({
      client,
      taskId: id,
      respond: (requestId, decision) => void state.executor?.respond(requestId, decision),
      onLeaseLost: () => halt({ kind: "lease_lost", reason: "o painel recusou a consulta de permissões" }),
      initialRules: task.permissionRules,
      log: (line) => log(`[${task.key}] ${line}`),
      sleep,
    });
    state.relay = relay;
    // Worker mode: the agent never sees the worker/git tokens (allowlisted env) and gets its own
    // temp dir next to its clone. True isolation between tasks is one task per container.
    const agentTmp = `${clone}.tmp`;
    mkdirSync(agentTmp, { recursive: true, mode: 0o700 });
    const envOptions = { mode: "allowlist", extra: { TMPDIR: agentTmp, TMP: agentTmp, TEMP: agentTmp } } as const;
    const running = startExecutor(command, clone, task.limits.maxRunMinutes * 60_000, (event) => {
      if (event.type === "permission_request") {
        const outcome = answerPermission(event, clone, task.settings, relay.rules(), relay.allowAll(), task.autoApprove === true);
        if (outcome) {
          running.respond(event.requestId, outcome.decision);
          emit([outcome.report]);
          return;
        }
        // Needs a human: the panel shows it like a local prompt and the relay waits for the answer.
        emit([event]);
        relay.ask(event);
        return;
      }
      if (event.type === "error" || (event.type === "result" && event.isError)) state.agentError = true;
      if (event.type === "text" && parseMarkers(event.text).some((m) => m.kind === "question")) state.asked = true;
      emit([relativize(event, clone)]);
    }, envOptions);
    state.executor = running;
    if (state.stop) running.cancel();
    const exit = await running.done;
    state.executor = null;
    relay.stop();

    const afterRun = stopped();
    if (afterRun) return await afterRun;
    if (exit.timedOut) return await fail(`tempo limite (${task.limits.maxRunMinutes} min) atingido`);
    // Same order as the local runner: a question wins over the exit code. Nothing is delivered:
    // the answer requeues the task and the next run gets the decisions in its prompt.
    if (state.asked) {
      log(`[${task.key}] o agente fez uma pergunta; aguardando resposta no painel`);
      return await report("waiting");
    }
    if (exit.code !== 0 || state.agentError) return await fail(`agente saiu com código ${exit.code}: ${lastLine(exit.stderrTail)}`);
    return await deliver(clone);
  } catch (error) {
    return (await stopped()) ?? (await fail(`falha inesperada no worker: ${message(error)}`));
  } finally {
    clearInterval(heartbeat);
    state.relay?.stop();
    deps.signal?.removeEventListener("abort", onShutdown);
    state.executor?.cancel();
    if (prepared) cleanup(prepared.path);
    rmSync(baseBundle, { force: true });
    client.discard(id);
  }

  async function deliver(clone: string): Promise<RunOutcome> {
    let commit: string | null;
    try {
      commit = await commitAll(clone, commitMessage(task), deps.identity ?? DEFAULT_IDENTITY);
    } catch (error) {
      return fail(`commit falhou: ${message(error)}`);
    }
    // Same as the local runner: no changes is a finished task with nothing to deliver.
    if (!commit) return report("done", { commit: null });

    let delivery: Awaited<ReturnType<typeof deliverCode>>;
    try {
      delivery = await deliverCode(clone, task, { gitToken, allowBundleFallback: true, log: (line) => log(`[${task.key}] ${line}`) });
    } catch (error) {
      return fail(`entrega falhou: ${message(error)}`);
    }
    if (delivery.transport === "bundle") {
      const limitMb = deps.maxBundleMb ?? DEFAULT_MAX_BUNDLE_MB;
      const size = statSync(delivery.bundleFile).size;
      if (size > limitMb * MB) return fail(`resultado maior que ${limitMb} MB (${Math.ceil(size / MB)} MB)`);
      try {
        if ((await retrying("upload do bundle", () => client.uploadBundle(id, delivery.bundleFile))) === LEASE_LOST) return "lease_lost";
      } catch (error) {
        return fail(error instanceof BundleTooLarge ? message(error) : `upload do resultado falhou: ${message(error)}`);
      }
    }
    if (state.stop?.kind === "lease_lost") return "lease_lost";
    log(`[${task.key}] entregue via ${delivery.transport} (${delivery.commit.slice(0, 12)})`);
    return report("done", { commit: delivery.commit, transport: delivery.transport });
  }
}
